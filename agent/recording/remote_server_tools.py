"""Controlled v3 server-tools protocol over an existing MCP call transport.

No local target.server import, no OS implementation, no public-v3 gate change.
Transport accepts (tool_name, arguments) and returns the decoded tool mapping.
No automatic retries: a lost response after a GUI call is an unknown outcome.
"""
from __future__ import annotations

import json
from collections.abc import Mapping


class McpServerTools:
    def __init__(self, call_tool):
        self._transport = call_tool
        self._run_token = None
        self._run_id = None
        self._binding_facade_holder = {}

    def _call(self, name, args):
        result = self._transport(name, dict(args))
        if not isinstance(result, Mapping):
            raise ValueError(f'{name}: malformed MCP tool result')
        return dict(result)

    def _json(self, name, **args):
        return json.dumps(self._call(name, args), ensure_ascii=False)

    def begin_product_run(self, profile_id, digest, lease_seconds=300):
        if self._run_token is not None:
            raise ValueError('remote product run already owned by this adapter')
        result = self._call('begin_product_run', dict(profile_id=profile_id,
                            digest=digest, lease_seconds=lease_seconds))
        if result.get('ok') is True:
            if not result.get('run_id') or not result.get('run_token'):
                raise ValueError('remote begin omitted run identity')
            self._run_id, self._run_token = result['run_id'], result['run_token']
            self._binding_facade_holder = {'facade': _RemoteBindingView(self)}
        return json.dumps(result, ensure_ascii=False)

    def end_product_run(self, run_token):
        try:
            result = self._call('end_product_run', dict(run_token=run_token))
        finally:
            self._binding_facade_holder = {}
        if result.get('ok') is True:
            self._run_id = self._run_token = None
        return json.dumps(result, ensure_ascii=False)

    def register_window_declaration(self, declarations_json, run_token):
        return self._json('register_window_declaration', declarations_json=declarations_json,
                          run_token=run_token)

    def bind_entry_window(self, window_id, identity, run_token, control_selector=None):
        return self._json('bind_entry_window', window_id=window_id, identity=identity,
                          run_token=run_token, control_selector=control_selector)

    def reverify_bound_window(self, window_id, binding_token, run_token):
        return self._json('reverify_bound_window', window_id=window_id,
                          binding_token=binding_token, run_token=run_token)

    def focus_bound_window(self, window_id, binding_token, run_token,
                           action_id='gui.click', action_args=None, request_id=None,
                           target_ref=None, observe=False, read_only=False):
        # null is meaningful: omitted action_id defaults to gui.click remotely.
        try:
            return self._json('focus_bound_window', window_id=window_id,
                              binding_token=binding_token, run_token=run_token,
                              action_id=action_id, action_args=action_args,
                              request_id=request_id, target_ref=target_ref,
                              observe=observe, read_only=read_only)
        except Exception:
            # A response can be lost AFTER injection. Feed the executor's
            # existing durable unknown latch, never replay the request.
            return json.dumps({'ok': False,
                               'code': ('post_state_observation_failed' if action_id is None
                                        else 'window_binding_dispatch_unknown'),
                               'executed': False if action_id is None else 'unknown'})

    def observe_product_windows(self, run_token):
        return self._json('observe_product_windows', run_token=run_token)


class _RemoteBindingView:
    """Read actual remote revision under the lease that produced the run ID.

    window_binding_state checks the current remote facade and binding token.
    No revision, observation or success is generated by this view. Effects not
    exposed by the remote tool protocol remain unsupported, not fake receipts.
    """
    def __init__(self, tools):
        self._tools = tools

    def step_context(self, *, run_id, step_id, attempt_id, window_id, binding_token):
        tools = self._tools
        if run_id != tools._run_id or tools._run_token is None:
            raise ValueError('window_binding_run_mismatch')
        state = tools._call('window_binding_state', dict(window_id=window_id,
                            binding_token=binding_token, run_token=tools._run_token))
        revision = state.get('revision')
        if (state.get('ok') is not True or type(revision) is not int or revision < 1
                or state.get('state') not in {'BOUND', 'HIDDEN', 'LOST'}):
            raise ValueError(state.get('code') or 'remote binding state unavailable')
        return {'bindingRevision': revision, 'generation': state.get('generation'),
                'state': state['state']}
